def breadcrumbs_html(trail):
    """trail: [(label, href_or_None)] — last item is the current page."""
    items = []
    for label, href in trail:
        if href:
            items.append('      <li><a href="%s">%s</a></li>' % (href, esc(label)))
        else:
            items.append('      <li><span aria-current="page">%s</span></li>' % esc(label))
    return ('\n<nav class="breadcrumbs" aria-label="Breadcrumb">\n  <ol>\n'
            + "\n".join(items) + "\n  </ol>\n</nav>\n")


