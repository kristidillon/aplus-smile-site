def build_service(s):
    path = "/services/%s/" % s["slug"]
    url = SITE + path
    trail = [("Home", "/"), ("Services", "/services/"), (s["nav"], None)]

    parts = [render_body_blocks(s["body"])]
    if s.get("steps"):
        parts.append(render_steps(s["steps"]))
    if s.get("emergency_list"):
        parts.append("  <ul>\n" + "\n".join(
            "    <li><strong>%s</strong> — %s</li>" % (esc(t), inline(b))
            for t, b in s["emergency_list"]) + "\n  </ul>")
    if s.get("body_after"):
        parts.append(render_body_blocks(s["body_after"]))

    nodes = [
        practice_node(),
        webpage_node(url, s["title"], s["desc"], trail),
        breadcrumb_node(url, trail),
        {
            "@type": "Service",
            "@id": url + "#service",
            "name": "%s in Fort Lauderdale, FL" % s["service_type"],
            "serviceType": s["service_type"],
            "description": plain(s["lede"]),
            "url": url,
            "provider": {"@id": SITE + "/#practice"},
            "areaServed": [{"@type": "City", "name": c, "addressRegion": "FL"}
                           for c in P["area_served"]],
            "audience": {"@type": "Audience", "audienceType": "Dental patients"},
        },
        faq_node(url, s["faqs"]),
    ]

    doc = head_html(title=s["title"], desc=s["desc"], path=path,
                    og_image="before-after.jpg", og_type="article",
                    extra=jsonld(nodes))
    doc += nav_html()
    doc += breadcrumbs_html(trail)
    doc += f"""
<header class="page-hero">
  <h1>{esc(s['h1'])}</h1>
  <p class="lede">{inline(s['lede'])}</p>
  <div class="hero-actions">
    <a class="btn" href="tel:{P['phone_e164']}">Call {P['phone_display']}</a>
    <a class="btn-link" href="#faq">Common questions</a>
  </div>
</header>

<section class="section">
  <div class="prose">
{chr(10).join(parts)}
  </div>
</section>
"""
    doc += render_faqs(s["faqs"])
    doc += related_html(s["related"])
    doc += cta_band_html(
        "See us in Fort Lauderdale",
        "A+ Smile is accepting new patients on North Federal Highway. Call the office, "
        "or email and we&rsquo;ll reach out within one business day.")
    doc += footer_html()
    write("services/%s/index.html" % s["slug"], doc)


