def breadcrumb_node(page_url, trail):
    return {
        "@type": "BreadcrumbList",
        "@id": page_url + "#breadcrumb",
        "itemListElement": [{
            "@type": "ListItem",
            "position": i + 1,
            "name": label,
            "item": SITE + (href if href else page_url.replace(SITE, "")),
        } for i, (label, href) in enumerate(trail)],
    }


def webpage_node(page_url, title, desc, trail, primary_image=None):
    node = {
        "@type": "WebPage",
        "@id": page_url + "#webpage",
        "url": page_url,
        "name": title,
        "description": desc,
        "isPartOf": {"@id": SITE + "/#website"},
        "about": {"@id": SITE + "/#practice"},
        "inLanguage": "en-US",
    }
    if trail:
        node["breadcrumb"] = {"@id": page_url + "#breadcrumb"}
    if primary_image:
        node["primaryImageOfPage"] = SITE + "/assets/" + primary_image
    return node


def faq_node(page_url, faqs):
    return {
        "@type": "FAQPage",
        "@id": page_url + "#faq",
        "mainEntity": [{
            "@type": "Question",
            "name": plain(q),
            "acceptedAnswer": {"@type": "Answer", "text": plain(a)},
        } for q, a in faqs],
    }


def jsonld(nodes):
    import json
    graph = {"@context": "https://schema.org", "@graph": nodes}
    return ('<script type="application/ld+json">\n'
            + json.dumps(graph, indent=2, ensure_ascii=False) + "\n</script>\n")


# ------------------------------------------------------------- page bodies
def render_body_blocks(blocks):
    out = []
    for heading, *rest in blocks:
        out.append("  <h2>%s</h2>" % esc(heading))
        for chunk in rest[0] if rest else []:
            if chunk is None:
                continue
            if isinstance(chunk, list):
                out.append("  <ul>")
                out += ["    <li>%s</li>" % inline(i) for i in chunk]
                out.append("  </ul>")
            else:
                out.append("  <p>%s</p>" % inline(chunk))
    return "\n".join(out)


def render_steps(steps):
    lis = "\n".join(
        "    <li><strong>%s</strong>%s</li>" % (esc(t), inline(b)) for t, b in steps)
    return '  <ol class="steps">\n%s\n  </ol>' % lis


def render_faqs(faqs):
    items = "\n".join(
        "    <details>\n      <summary>%s</summary>\n      <p>%s</p>\n    </details>"
        % (inline(q), inline(a)) for q, a in faqs)
    return ('\n<section class="section" id="faq">\n  <h2>Questions patients ask</h2>\n'
            '  <div class="faq">\n%s\n  </div>\n</section>\n' % items)


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("  wrote %-52s %6d bytes" % (path, len(text.encode("utf-8"))))


